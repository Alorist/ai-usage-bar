"""Generates skin/AIUsageBar/Taskbar.ini and Mini.ini from one layout definition.

Run after changing the layout:  python tools/gen_skins.py
Section widths here must match SEC_W in skin/AIUsageBar/@Resources/AIUsage.lua.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIN = os.path.join(ROOT, "skin", "AIUsageBar")
VERSION = "1.0.0"

SERVICES = [("CL", "Claude", 74, "Claude"), ("CX", "Codex", 70, "Codex")]  # prefix, label, name width, group
VARIANTS = {
    "Taskbar": dict(h=32, font=11, zpos=2, other="Mini", other_title="Show as desktop bar instead",
                    note="Sits on the taskbar left of the tray; hidden while something is fullscreen."),
    "Mini": dict(h=44, font=12, zpos=-2, other="Taskbar", other_title="Show on the taskbar instead",
                 note="Centred at the top of the main screen, on the desktop layer."),
}


def build(variant, v):
    h, cy = v["h"], v["h"] // 2
    L = []
    a = L.append
    on_refresh = f"[!Draggable 0][!ZPos {v['zpos']}]"
    on_close = ""
    if variant == "Taskbar":
        on_refresh = ('[!WriteKeyValue Watch active 1 "#FlagFile#"]' + on_refresh +
                      '["#Exe#" helper --config "#CURRENTCONFIG#" --ini "#CURRENTPATH##CURRENTFILE#"'
                      ' --flag "#FlagFile#" --rainmeter "#PROGRAMPATH#Rainmeter.exe"]')
        on_close = '\nOnCloseAction=[!WriteKeyValue Watch active 0 "#FlagFile#"]'
    a(f"""; AI Usage Bar ({variant}) - Claude / Codex plan limits and token value at a glance.
; {v['note']}
; Generated by tools/gen_skins.py - edit that instead of this file.

[Rainmeter]
Update=30000
AccurateText=1
DynamicWindowSize=1
OnRefreshAction={on_refresh}{on_close}
ContextTitle=Refresh usage now
ContextAction=[!CommandMeasure MeasureRun "Run"]
ContextTitle2={v['other_title']}
ContextAction2=[!ActivateConfig "#CURRENTCONFIG#" "{v['other']}.ini"]
ContextTitle3=Open data folder
ContextAction3=["#DataDir#"]

[Metadata]
Name=AI Usage Bar ({variant})
Author=Alorist
Information=Shows Claude and Codex subscription limits and token usage. Hover a section for reset times and details.
Version={VERSION}
License=MIT

[Variables]
Variant={variant}
Exe=#@#bin\\aiusage\\aiusage.exe
DataDir=#@#data
DataFile=#@#data\\rainmeter_data.txt
FlagFile=#@#taskbar_active.flag
UpdatedColor=255,255,255,105
CLX=18
CXX=374
TKX=726
Div1X=356
Div2X=708
BgW=900
TKOn=0
TodayShort=-
WeekShort=-
TokTip=waiting for data""")
    for p, *_ in SERVICES:
        a(f"{p}Dot=255,255,255,105\n{p}Tip=waiting for data")
        for i in (1, 2):
            a(f"{p}Pct{i}=-\n{p}PctColor{i}=255,255,255,240\n{p}W{i}=6\n{p}Fill{i}=0,0,0,0")

    a(f"""
; ---------------------------------------------------------------- measures

[MeasureScript]
Measure=Script
ScriptFile=#@#AIUsage.lua

; counts skin updates 1..10 (30 s each): fetch at load and every 5 minutes
[MeasureCollect]
Measure=Calc
Formula=(MeasureCollect % 10) + 1
IfCondition=MeasureCollect = 1
IfTrueAction=[!CommandMeasure MeasureRun "Run"]

; runs the fetch, then redraws as soon as it finishes
[MeasureRun]
Measure=Plugin
Plugin=RunCommand
Program="#Exe#"
Parameter=collect --data-dir "#DataDir#"
State=Hide
FinishAction=[!CommandMeasure MeasureScript "Refresh()"][!UpdateMeter *][!Redraw]

; ------------------------------------------------------------------ styles

[sText]
FontFace=Segoe UI
FontSize={v['font']}
FontColor=255,255,255,235
AntiAlias=1
StringAlign=LeftCenter
Y={cy}
DynamicVariables=1

[sDim]
FontColor=255,255,255,140

[sBold]
StringStyle=Bold

; ------------------------------------------------------------------ meters

[Bg]
Meter=Shape
X=0
Y=0
DynamicVariables=1
Shape=Rectangle 0.5,0.5,(#TKOn# = 1 ? [WeekVal:X]+[WeekVal:W]+18 : #BgW#),{h - 1},{(h - 1) / 2} | Fill Color 12,16,22,185 | Stroke Color 255,255,255,30 | StrokeWidth 1
""")

    for p, name, nw, group in SERVICES:
        a(f"""; {name}
[{p}DotM]
Meter=Shape
Group={group}
X=(#{p}X#)
Y={cy - 4}
DynamicVariables=1
Shape=Ellipse 4,4,4 | Fill Color #{p}Dot# | StrokeWidth 0

[{p}Name]
Meter=String
MeterStyle=sText | sBold
Group={group}
Text={name}
X=(#{p}X#+14)
""")
        for i, (lab, off) in enumerate((("5h", 0), ("wk", 130)), 1):
            a(f"""[{p}Lab{i}]
Meter=String
MeterStyle=sText | sDim
Group={group}
Text={lab}
X=(#{p}X#+{nw + off})

[{p}Bar{i}]
Meter=Shape
Group={group}
X=(#{p}X#+{nw + off + 20})
Y={cy - 3}
DynamicVariables=1
Shape=Rectangle 0,0,56,6,3 | Fill Color 255,255,255,38 | StrokeWidth 0
Shape2=Rectangle 0,0,#{p}W{i}#,6,3 | Fill Color #{p}Fill{i}# | StrokeWidth 0

[{p}Pct{i}M]
Meter=String
MeterStyle=sText | sBold
Group={group}
FontColor=#{p}PctColor{i}#
Text=#{p}Pct{i}#
X=(#{p}X#+{nw + off + 82})
""")

    for i in (1, 2):
        a(f"""[Div{i}]
Meter=Shape
Group=Div{i}
X=(#Div{i}X#)
Y={cy - 9}
DynamicVariables=1
Shape=Rectangle 0,0,1,18 | Fill Color 255,255,255,40 | StrokeWidth 0
""")

    a(f"""; Tokens (API-equivalent value; only when ccusage is installed)
[TodayLab]
Meter=String
MeterStyle=sText | sDim
Group=Tokens
FontColor=#UpdatedColor#
Text=1d
X=(#TKX#)

[TodayVal]
Meter=String
MeterStyle=sText | sBold
Group=Tokens
Text=#TodayShort#
X=6R

[WeekLab]
Meter=String
MeterStyle=sText | sDim
Group=Tokens
Text=7d
X=14R

[WeekVal]
Meter=String
MeterStyle=sText | sBold
Group=Tokens
Text=#WeekShort#
X=6R

; ------------------------------------------- hover areas (tooltips with details)
""")
    widths = {"CL": 74 + 264, "CX": 70 + 264}
    for p, name, nw, group in SERVICES:
        a(f"""[{p}Hit]
Meter=Shape
Group={group}
X=(#{p}X#-10)
Y=0
DynamicVariables=1
Shape=Rectangle 0,0,{widths[p]},{h} | Fill Color 0,0,0,1 | StrokeWidth 0
ToolTipText=#{p}Tip#
""")
    a(f"""[TKHit]
Meter=Shape
Group=Tokens
X=(#TKX#-12)
Y=0
DynamicVariables=1
Shape=Rectangle 0,0,([WeekVal:X]+[WeekVal:W]-#TKX#+24),{h} | Fill Color 0,0,0,1 | StrokeWidth 0
ToolTipText=#TokTip#
""")
    return "\n".join(L)


if __name__ == "__main__":
    for name, v in VARIANTS.items():
        path = os.path.join(SKIN, f"{name}.ini")
        with open(path, "w", encoding="utf-8", newline="\r\n") as f:
            f.write(build(name, v))
        print("wrote", path)
